async function seedTickets() {
  console.log("=======================================================");
  console.log("   Starting Real-Life Ticket Seeding (100 Tickets)     ");
  console.log("=======================================================\n");

  try {
    // 1. Fetch available admin/agent users to link assignments
    const users = await prisma.user.findMany({
      where: { deletedAt: null },
      select: { id: true, name: true, email: true, role: true },
    });

    console.log(`[Seed] Found ${users.length} active users for ticket assignments.`);
    const agentUsers = users.filter((u) => u.role === "agent" || u.role === "admin");

    const now = Date.now();
    let createdCount = 0;

    for (let i = 0; i < SEED_TICKETS.length; i++) {
      const item = SEED_TICKETS[i];

      // Stagger creation dates based on hoursAgo
      const createdAt = new Date(now - item.hoursAgo * 60 * 60 * 1000);
      const updatedAt = new Date(createdAt.getTime() + Math.min(item.hoursAgo * 30 * 60 * 1000, 2 * 60 * 60 * 1000));

      // Randomly assign some in_progress, resolved, or closed tickets to available agents
      let assignedToId: string | null = null;
      if (item.status !== "open" && agentUsers.length > 0) {
        const assignedUser = agentUsers[i % agentUsers.length];
        assignedToId = assignedUser.id;
      }

      // Generate messages: initial customer message + optional agent reply
      const messagesData: any[] = [
        {
          senderType: "customer",
          senderEmail: item.customerEmail,
          senderName: item.customerName,
          bodyText: item.description,
          createdAt: createdAt,
        },
      ];

      if (item.agentReply) {
        const agent = agentUsers.length > 0 ? agentUsers[i % agentUsers.length] : null;
        messagesData.push({
          senderType: "agent",
          senderEmail: agent?.email || "support@tickethelper.internal",
          senderName: agent?.name || "Support Staff",
          bodyText: item.agentReply,
          createdAt: updatedAt,
        });
      }

      // Atomically create Ticket and initial Messages
      await prisma.ticket.create({
        data: {
          subject: item.subject,
          description: item.description,
          status: item.status,
          priority: item.priority,
          customerEmail: item.customerEmail,
          customerName: item.customerName,
          recipientEmail: item.recipientEmail,
          assignedToId: assignedToId,
          source: "email",
          createdAt: createdAt,
          updatedAt: updatedAt,
          messages: {
            create: messagesData,
          },
        },
      });

      createdCount++;
    }

    console.log(`[Seed] Successfully seeded ${createdCount} diverse real-life tickets!`);

    // Output stats
    const totalCount = await prisma.ticket.count();
    const openCount = await prisma.ticket.count({ where: { status: "open" } });
    const inProgressCount = await prisma.ticket.count({ where: { status: "in_progress" } });
    const resolvedCount = await prisma.ticket.count({ where: { status: "resolved" } });
    const closedCount = await prisma.ticket.count({ where: { status: "closed" } });

    const urgentCount = await prisma.ticket.count({ where: { priority: "urgent" } });
    const highCount = await prisma.ticket.count({ where: { priority: "high" } });
    const mediumCount = await prisma.ticket.count({ where: { priority: "medium" } });
    const lowCount = await prisma.ticket.count({ where: { priority: "low" } });

    console.log("\n--- Database Ticket Statistics ---");
    console.log(`Total Tickets in DB: ${totalCount}`);
    console.log(`Status Breakdown:`);
    console.log(`  - Open:        ${openCount}`);
    console.log(`  - In Progress: ${inProgressCount}`);
    console.log(`  - Resolved:    ${resolvedCount}`);
    console.log(`  - Closed:      ${closedCount}`);
    console.log(`Priority Breakdown:`);
    console.log(`  - Urgent:      ${urgentCount}`);
    console.log(`  - High:        ${highCount}`);
    console.log(`  - Medium:      ${mediumCount}`);
    console.log(`  - Low:         ${lowCount}`);
    console.log("=======================================================\n");
  } catch (error) {
    console.error("[Seed] Failed to seed tickets:", error);
    process.exit(1);
  } finally {
    await prisma.$disconnect();
  }
}

seedTickets();

